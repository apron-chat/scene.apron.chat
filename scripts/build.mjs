// Bundles scenes/*.jsonl into src/scenes.gen.ts, so the Worker serves them
// without a fetch or storage read. Run by `npm run build`, which wrangler
// runs before `dev` and `deploy` (wrangler.jsonc).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const NAME = /^[a-z0-9][a-z0-9-]{0,63}$/;
const scenes = {};
for (const file of readdirSync(join(root, "scenes")).sort()) {
	if (!file.endsWith(".jsonl")) continue;
	const name = file.slice(0, -".jsonl".length);
	if (!NAME.test(name)) throw new Error(`scenes/${file}: a scene's name is lowercase letters, digits and dashes`);
	scenes[name] = readFileSync(join(root, "scenes", file), "utf8");
}
writeFileSync(join(root, "src", "scenes.gen.ts"), `// Generated by scripts/build.mjs from scenes/*.jsonl. Do not edit.\nexport const SCENES: Record<string, string> = ${JSON.stringify(scenes, null, "\t")};\n`);
console.log(`Bundled ${Object.keys(scenes).length} scene(s): ${Object.keys(scenes).join(", ")}`);
